//! MaeclyPrint Tauri backend.
//!
//! At this milestone the backend is intentionally minimal: it boots a Tauri
//! window and exposes a single diagnostic IPC command (`app_info`) so the
//! frontend can verify the React ↔ Rust bridge is healthy.
//!
//! Real printing logic (queue, SumatraPDF adapter, profile persistence, CLI)
//! lands in the M1 plan.

pub mod ipc;
pub mod logging;
pub mod settings;
pub mod util;

use tauri::Manager;

#[cfg_attr(mobile, tauri::mobile_entry_point)]
pub fn run() {
    // Initialize structured logging as early as possible so any startup error
    // is captured to disk.
    if let Err(e) = logging::init() {
        eprintln!("logging init failed: {e}");
    }

    let builder = tauri_specta::Builder::<tauri::Wry>::new()
        .commands(tauri_specta::collect_commands![ipc::diag::app_info]);

    // `@ts-nocheck` disables strict TS checks (notably `noUnusedLocals`)
    // for the generated file so tauri-specta scaffolding like
    // `__makeEvents__` and `TAURI_CHANNEL` doesn't break CI typecheck.
    // The file is rebuilt on every cargo build and never hand-edited.
    #[cfg(debug_assertions)]
    builder
        .export(
            specta_typescript::Typescript::default().header(
                "// @ts-nocheck\n/* eslint-disable */\n// AUTO-GENERATED by tauri-specta. Do not edit by hand.\n",
            ),
            "../src/ipc/bindings.ts",
        )
        .expect("failed to export typescript bindings");

    tauri::Builder::default()
        .invoke_handler(builder.invoke_handler())
        .setup(move |app| {
            builder.mount_events(app);

            tracing::info!(
                event = "app_started",
                version = env!("CARGO_PKG_VERSION"),
                build_date = env!("BUILD_DATE"),
                "MaeclyPrint started"
            );

            // Resolve the window so failures here surface as setup errors,
            // not silent missing-window bugs.
            if let Some(_main) = app.get_webview_window("main") {
                tracing::debug!(event = "main_window_resolved");
            } else {
                tracing::warn!(event = "main_window_missing");
            }
            Ok(())
        })
        .run(tauri::generate_context!())
        .expect("error while running tauri application");
}
