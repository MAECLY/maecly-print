export function mkFile(
  name: string,
  ext: string,
  kb: number,
  status: UiFile['status'] = 'queued',
  pages?: number,
  progress?: number,
): UiFile {
  return {
    id: `${name}_${ext}`,
    name,
    ext,
    kb,
    status,
    pages: pages ?? null,
    progress: progress ?? 0,
  };
}

